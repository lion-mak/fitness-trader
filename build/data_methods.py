def _gen(base_name, display, grams, cat, method_name, tpl, extras, ratio):
    items = [(base_name, grams)] + list(extras)
    total = grams + sum(g for _, g in extras)
    yield_g = int(round(total * ratio))
    alias = ''
    D(tpl.format(display), alias, cat, items, yield_g, unit='份', gram=yield_g, src=SRC_CALC)


